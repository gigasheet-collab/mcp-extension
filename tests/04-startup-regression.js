process.env.GIGASHEET_TOKEN=''; process.env.GIGASHEET_CLIENT_ID='test-client';
process.env.GIGASHEET_KEYCHAIN_SERVICE='com.gigasheet.claude-extension.test'; process.env.GIGASHEET_NO_BROWSER='1';
const path=require('path'); const srv=path.resolve(process.argv[2]);
const auth=require(path.join(srv,'auth.js')); const bridge=require(path.join(srv,'index.js'));
let fails=0; const check=(l,ok,x='')=>{console.log(`  ${ok?'PASS':'FAIL'}  ${l}${x?'  -> '+x:''}`); if(!ok) fails++;};
(async()=>{
  const mem={refresh_token:'rt-good'}; let flows=0;
  auth._hooks.keychain={setSecret:async(a,s)=>{mem[a]=s;},getSecret:async(a)=>mem[a]??null,deleteSecret:async(a)=>{delete mem[a];}};
  auth._hooks.postForm=async(url,f)=>{ if(url.includes('device/code')){flows++;return{status:200,json:{device_code:'dc',user_code:'X-'+flows,verification_uri_complete:'https://x',interval:1,expires_in:300}};} if(f.grant_type==='refresh_token')return{status:200,json:{access_token:'tok',expires_in:3600,refresh_token:'rt-good'}}; return{status:400,json:{error:'authorization_pending'}};};
  const REJ='{"Success":false,"Message":"Unauthorized"}';
  console.log('### B1. the reinstall bug: unauthenticated prompts/list + resources/list refused by remote');
  let r=await bridge.interpret(403,REJ,2,'prompts/list',false);
  check('prompts/list answered locally with empty list', r.result && Array.isArray(r.result.prompts) && r.result.prompts.length===0);
  r=await bridge.interpret(403,REJ,3,'resources/list',false);
  check('resources/list answered locally with empty list', r.result && Array.isArray(r.result.resources));
  check('stored credential NOT wiped', mem.refresh_token==='rt-good');
  check('no device flow started', flows===0);
  console.log('### B2. some other unauthenticated method refused -> plain error, credential intact');
  r=await bridge.interpret(401,REJ,4,'completion/complete',false);
  check('JSON-RPC error, not a re-auth', r.error && r.error.code===-32002, r.error&&r.error.message);
  check('credential intact', mem.refresh_token==='rt-good'); check('still no flow', flows===0);
  console.log('### B3. tools/call WITH our bearer refused -> logout + re-auth (the one legitimate case)');
  r=await bridge.interpret(401,REJ,5,'tools/call',true);
  check('credential erased', mem.refresh_token===undefined); check('one flow started', flows===1);
  check('re-auth message', /sign-in has expired/.test(r.result.content[0].text));
  console.log('### B4. tools/call refused but NO bearer was sent -> must not wipe');
  mem.refresh_token='rt-good';
  r=await bridge.interpret(401,REJ,6,'tools/call',false);
  check('credential intact', mem.refresh_token==='rt-good'); check('no extra flow', flows===1);
  console.log(fails?`\n${fails} FAILED`:'\nALL BUG-REGRESSION TESTS PASSED'); process.exit(fails?1:0);
})().catch(e=>{console.error('CRASH',e);process.exit(2);});
